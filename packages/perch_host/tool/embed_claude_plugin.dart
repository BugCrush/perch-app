// Writes the Perch plugin's hooks/hooks.json (the `/perch` module plus Perch's hooks, from
// lib/src/hooks.dart) and copies the plugin (claude_plugin/perch) into
// lib/src/claude_plugin_files.dart, so the compiled host can install it. Run from
// packages/perch_host after editing the plugin or the hooks:
//   dart run tool/embed_claude_plugin.dart
// (test/commands_install_test.dart fails while the two differ.)
import 'dart:convert';
import 'dart:io';

import 'package:perch_host/src/hooks.dart';

/// The plugin's files, by path relative to its folder (forward slashes), in a stable order.
const pluginFiles = [
  '.claude-plugin/plugin.json',
  'hooks/hooks.json',
  'hooks/register.tsx',
  'hooks/perch-setup.sh',
];

/// hooks/hooks.json: the menu module and Perch's hooks.
String hooksJson() => '${const JsonEncoder.withIndent('  ').convert({
      'description': "Perch: /perch (the task board menu) and the hooks that tell the Perch host on this machine "
          'about each session event (questions, permissions, plans, turns ending, usage limits).',
      'modules': ['./register.tsx'],
      ...perchPluginHooks(),
    })}\n';

String embedded(String root) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/embed_claude_plugin.dart from claude_plugin/perch: do not edit by hand.')
    ..writeln('// The Perch plugin (/perch and the hooks) that `perch_host commands install` writes into Claude Code.')
    ..writeln()
    ..writeln('const claudePluginFiles = <String, String>{');
  for (final f in pluginFiles) {
    final text = File('$root/$f').readAsStringSync().replaceAll('\r\n', '\n');
    if (text.contains("'''")) throw StateError("$f holds ''' and cannot be embedded.");
    out.writeln("  '$f': r'''$text''',");
  }
  out.writeln('};');
  return out.toString();
}

void main() {
  File('claude_plugin/perch/hooks/hooks.json').writeAsStringSync(hooksJson());
  File('lib/src/claude_plugin_files.dart').writeAsStringSync(embedded('claude_plugin/perch'));
  stdout.writeln('Wrote claude_plugin/perch/hooks/hooks.json and lib/src/claude_plugin_files.dart');
}
