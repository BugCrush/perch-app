import 'dart:convert';
import 'dart:io';

import 'package:perch_host/src/transcript.dart';
import 'package:perch_protocol/perch_protocol.dart';
import 'package:test/test.dart';

const fixtureId = '11111111-2222-4333-8444-555555555555';

void main() {
  test('maps_user_assistant_and_tool_lines', () {
    final lines = File('test/fixtures/transcript/$fixtureId.jsonl').readAsLinesSync().map(parseTranscriptLine).toList();
    final events = [for (final l in lines) if (l is TranscriptEvents) ...l.events];
    expect(events.whereType<UserMessage>().map((e) => e.text),
        ['List the files here and count them.', 'Thanks, that is all.']);
    expect(events.whereType<AssistantText>().map((e) => e.text), contains("I'll list the files."));
    expect(events.whereType<ToolCall>().map((e) => e.name), ['Bash', 'Agent']);
    expect(events.whereType<ToolResult>().first.text, 'a.txt\nb.txt');
    expect(events.every((e) => e.parentToolUseId == null), isTrue);
  });

  test('skips_reminders_and_bookkeeping', () {
    final reminder = jsonEncode({
      'type': 'user',
      'message': {'role': 'user', 'content': '<system-reminder>x</system-reminder>'},
    });
    expect(parseTranscriptLine(reminder), isA<TranscriptSkip>());
    for (final prefix in ['<command-name>', '<local-command-stdout>', '<task-notification>']) {
      final l = jsonEncode({
        'type': 'user',
        'message': {
          'role': 'user',
          'content': [
            {'type': 'text', 'text': '${prefix}x'}
          ]
        },
      });
      expect(parseTranscriptLine(l), isA<TranscriptSkip>(), reason: prefix);
    }
    for (final t in ['api-request', 'api-request-blob', 'attachment', 'mode', 'last-prompt', 'session-owner', 'atis-latch', 'system']) {
      expect(parseTranscriptLine(jsonEncode({'type': t, 'sessionId': 's'})), isA<TranscriptSkip>(), reason: t);
    }
  });

  test('slash_commands_and_their_output_are_shown_caveats_and_expanded_prompts_are_not', () {
    String user(Object content, {bool meta = false}) => jsonEncode({
          'type': 'user',
          if (meta) 'isMeta': true,
          'timestamp': '2026-11-16T10:00:00.000Z',
          'message': {'role': 'user', 'content': content},
        });
    final cmd = parseTranscriptLine(user(
        '<command-name>/context</command-name>\n            <command-message>context</command-message>\n            <command-args></command-args>'));
    final c = (cmd as TranscriptEvents).events.single as SlashCommand;
    expect((c.name, c.args), ('/context', ''));
    expect(c.atMs, greaterThan(0));
    expect(cmd.ownerPromptAtMs, isNull, reason: 'not a message to Claude');
    // The other order Claude Code writes for prompt commands (skills), with arguments.
    final skill = parseTranscriptLine(user(
        '<command-message>init is analyzing your codebase…</command-message>\n<command-name>/init</command-name>\n<command-args>quick</command-args>'));
    expect(((skill as TranscriptEvents).events.single as SlashCommand).line, '/init quick');
    final out = parseTranscriptLine(user([
      {'type': 'text', 'text': '<local-command-stdout>\u001b[1mContext Usage\u001b[22m\n| Category | Tokens |\n|---|---|\n| System | 3k |</local-command-stdout>'}
    ]));
    final o = (out as TranscriptEvents).events.single as CommandOutput;
    expect(o.text, 'Context Usage\n| Category | Tokens |\n|---|---|\n| System | 3k |', reason: 'terminal colours removed');
    expect(o.isError, isFalse);
    final err = parseTranscriptLine(user('<local-command-stderr>Unknown skill: nope</local-command-stderr>'));
    expect(((err as TranscriptEvents).events.single as CommandOutput).isError, isTrue);
    // Meta lines: the caveat stays hidden; a command output marked meta is still shown.
    expect(
        parseTranscriptLine(user('<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>', meta: true)),
        isA<TranscriptSkip>());
    expect(parseTranscriptLine(user('<local-command-stdout>Set model to haiku</local-command-stdout>', meta: true)), isA<TranscriptEvents>());
    expect(parseTranscriptLine(user('<local-command-stdout></local-command-stdout>')), isA<TranscriptSkip>(), reason: 'nothing printed');
    expect(parseTranscriptLine(user('Expanded skill prompt text', meta: true)), isA<TranscriptSkip>());
  });

  test('slash_commands_as_claude_code_2_1_325_writes_them_system_local_command_lines', () {
    // The shape seen live (2026-11-16, Windows, 2.1.325); the text here is made up.
    String sys(String content, {bool displayOnly = false}) => jsonEncode({
          'type': 'system',
          'subtype': 'local_command',
          'content': content,
          'level': 'info',
          'timestamp': '2026-11-16T17:27:30.973Z',
          'isMeta': false,
          if (displayOnly) 'isDisplayOnly': true,
          if (displayOnly) 'commandRun': {'command': 'context', 'args': ''},
        });
    final c = parseTranscriptLine(sys(
        '<command-name>/context</command-name>\n            <command-message>context</command-message>\n            <command-args></command-args>'));
    expect(((c as TranscriptEvents).events.single as SlashCommand).name, '/context');
    final o = parseTranscriptLine(sys(
        '<local-command-stdout> \u001b[1mContext Usage\u001b[22m\n\u001b[38;2;136;136;136m⛀ \u001b[38;2;153;153;153m⛁ Model: test · 5k/200k</local-command-stdout>',
        displayOnly: true));
    expect(((o as TranscriptEvents).events.single as CommandOutput).text, 'Context Usage\n⛀ ⛁ Model: test · 5k/200k');
    expect(parseTranscriptLine(jsonEncode({'type': 'system', 'subtype': 'turn_duration', 'durationMs': 5})), isA<TranscriptSkip>());
  });

  test('title_and_permission_mode', () {
    final t = parseTranscriptLine('{"type":"ai-title","aiTitle":"Fix login"}');
    expect(t, isA<TranscriptTitle>());
    expect((t as TranscriptTitle).title, 'Fix login');
    final m = parseTranscriptLine('{"type":"permission-mode","permissionMode":"auto"}');
    expect((m as TranscriptPermissionMode).mode, 'auto');
  });

  test('malformed_line_is_skipped', () {
    for (final l in ['', '{', 'nope', '{"type":"something-new"}']) {
      expect(parseTranscriptLine(l), isA<TranscriptSkip>(), reason: l);
    }
    // A known type in a shape Perch cannot read carries no events and is reported (drift).
    for (final l in ['{"type":"user"}', '{"type":"assistant","message":"x"}']) {
      expect(parseTranscriptLine(l), isA<TranscriptMalformed>(), reason: l);
    }
  });

  test('subagent_lines_carry_the_given_parent', () {
    final l = File('test/fixtures/transcript/$fixtureId/subagents/agent-a1b2c3d4e5f6a7b8c.jsonl').readAsLinesSync();
    final e = parseTranscriptLine(l.first, parentToolUseId: 'toolu_A2') as TranscriptEvents;
    expect(e.events.single, isA<UserMessage>());
    expect(e.events.single.parentToolUseId, 'toolu_A2');
  });

  test('find_transcript_in_config_dir', () {
    final dir = Directory.systemTemp.createTempSync('perch_cfg_');
    addTearDown(() => dir.deleteSync(recursive: true));
    final p = Directory('${dir.path}/projects/D--projects-example')..createSync(recursive: true);
    File('${p.path}/$fixtureId.jsonl').writeAsStringSync('');
    expect(findTranscript(fixtureId, configDir: dir.path)?.path, endsWith('$fixtureId.jsonl'));
    expect(findTranscript('nope', configDir: dir.path), isNull);
    expect(claudeConfigDir(), isNotEmpty);
  });

  test('find_transcript_prefers_the_most_recently_written_copy', () {
    final sep = Platform.pathSeparator;
    final dir = Directory.systemTemp.createTempSync('perch_find_');
    addTearDown(() => dir.deleteSync(recursive: true));
    const id = 'aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee';
    // A stale copy left in a folder that sorts first, and the live one.
    final stale = File('${dir.path}${sep}projects${sep}A--old$sep$id.jsonl')..createSync(recursive: true);
    final live = File('${dir.path}${sep}projects${sep}Z--live$sep$id.jsonl')..createSync(recursive: true);
    stale.setLastModifiedSync(DateTime(2026, 11, 1));
    live.setLastModifiedSync(DateTime(2026, 11, 13));
    expect(findTranscript(id, configDir: dir.path)?.path, live.path);
  });

  test('latest_ai_title_is_read_from_the_end_across_chunks', () {
    final dir = Directory.systemTemp.createTempSync('perch_title_');
    addTearDown(() => dir.deleteSync(recursive: true));
    final f = File('${dir.path}${Platform.pathSeparator}t.jsonl');
    final filler = jsonEncode({'type': 'assistant', 'message': {'role': 'assistant', 'content': 'x' * 500}});
    final b = StringBuffer()
      ..writeln(jsonEncode({'type': 'ai-title', 'aiTitle': 'Old title'}))
      ..writeln(jsonEncode({'type': 'ai-title', 'aiTitle': 'Newer title'}));
    for (var i = 0; i < 300; i++) {
      b.writeln(filler); // pushes the titles more than one 64 KB chunk back
    }
    f.writeAsStringSync(b.toString());
    expect(latestAiTitle(f), 'Newer title');
    f.writeAsStringSync(filler);
    expect(latestAiTitle(f), isNull);
  });

  group('inbox messages', () {
    // As Claude Code 2.1.325 writes a message that arrived on the session's inbox
    // (synthetic text).
    String peerLine({Map<String, dynamic>? origin, String? content}) => jsonEncode({
          'type': 'user',
          'isMeta': true,
          'timestamp': '2026-11-14T12:00:00.000Z',
          'origin': origin ??
              {'kind': 'peer', 'from': 'unknown', 'verifiedPeerPid': 4242, 'name': 'perch-phone', 'body': 'Run the tests.'},
          'message': {
            'role': 'user',
            'content': content ??
                'Another Claude session sent a message:\n<cross-session-message from-name="perch-phone">\nRun the tests.\n'
                    '</cross-session-message>\n\nThis came from another Claude session — not typed by your user.',
          },
        });

    test('a message Perch sent shows as the user message', () {
      final l = parseTranscriptLine(peerLine());
      expect(l, isA<TranscriptEvents>());
      final e = (l as TranscriptEvents).events.single as UserMessage;
      expect(e.text, 'Run the tests.');
      expect(e.atMs, DateTime.utc(2026, 11, 14, 12).millisecondsSinceEpoch);
    });

    test('without origin.body the text comes from the wrapper', () {
      final l = parseTranscriptLine(
          peerLine(origin: {'kind': 'peer', 'from': 'unknown', 'name': 'perch-phone'}));
      expect(((l as TranscriptEvents).events.single as UserMessage).text, 'Run the tests.');
    });

    test('an escaped closing tag in the body is restored', () {
      final l = parseTranscriptLine(peerLine(origin: {
        'kind': 'peer',
        'from': 'unknown',
        'name': 'perch-phone',
        'body': r'a <\/cross-session-message> b',
      }));
      expect(((l as TranscriptEvents).events.single as UserMessage).text, 'a </cross-session-message> b');
    });

    test("other sessions' messages and other meta lines stay hidden", () {
      expect(
          parseTranscriptLine(peerLine(
              origin: {'kind': 'peer', 'from': 'unknown', 'name': 'api-worker', 'body': 'Schema changed.'})),
          isA<TranscriptSkip>());
      expect(parseTranscriptLine(peerLine(origin: {'kind': 'peer', 'from': 'unknown'}, content: 'Another Claude session sent a message:\nhi')),
          isA<TranscriptSkip>());
      expect(
          parseTranscriptLine(jsonEncode({
            'type': 'user',
            'isMeta': true,
            'message': {'role': 'user', 'content': 'Caveat: local commands.'},
          })),
          isA<TranscriptSkip>());
    });
  });
}
